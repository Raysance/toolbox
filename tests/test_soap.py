def test_one_time_credential_has_android_uri_encoding():
    from urllib.parse import parse_qs
    da = DAToken('<token a="x y"/>', KEY)
    credential = one_time_credential(da, now=100, nonce=NONCE)
    assert '%20' in credential and '+' not in credential
    pieces = parse_qs(credential)
    assert pieces['da'] == ['<token a="x y"/>']
    query, digest = credential.rsplit('&hash=', 1)
    from urllib.parse import unquote
    expected_key = bytes.fromhex('7b0edf4a43a82cdd12d15a6a6db59c6752999a7f79d0d61bcbd7398ddc8fab73')
    assert base64.b64decode(unquote(digest)) == hmac.new(expected_key, query.encode(), hashlib.sha256).digest()


