def test_device_registration_and_authentication_protocol():
    from lxml import etree
    client = SoapClient()
    calls = []
    def respond(url, root):
        calls.append((url, etree.tostring(root)))
        if 'deviceaddcredential' in url:
            assert root.find('ClientInfo').get('name') == 'MsaAndroidSdk/2.1.0524.0520'
            assert root.find('Authentication/Membername').text.startswith('02')
            assert len(root.find('Authentication/Password').text) == 16
            return b'', _parse(b'<DeviceAddResponse Success="true"><puid>device-puid</puid></DeviceAddResponse>')
        clear = ('<Envelope xmlns:wst="' + WST + '" xmlns:wsu="' + WSU + '" '
                 'xmlns:wsp="http://schemas.xmlsoap.org/ws/2004/09/policy" '
                 'xmlns:wsa="http://www.w3.org/2005/08/addressing">'
                 '<wsu:Timestamp><wsu:Expires>2099-01-01T00:00:00Z</wsu:Expires></wsu:Timestamp>'
                 '<wst:RequestSecurityTokenResponse><wst:TokenType>urn:passport:legacy</wst:TokenType>'
                 '<wst:Lifetime><wsu:Expires>2099-01-01T00:00:00Z</wsu:Expires></wst:Lifetime>'
                 '<wsp:AppliesTo><wsa:EndpointReference><wsa:Address>http://Passport.NET/tb</wsa:Address>'
                 '</wsa:EndpointReference></wsp:AppliesTo><wst:RequestedSecurityToken>'
                 '<EncryptedData xmlns="' + ENC + '"><CipherData><CipherValue>opaque</CipherValue>'
                 '</CipherData></EncryptedData></wst:RequestedSecurityToken><wst:RequestedProofToken>'
                 '<wst:BinarySecret>' + b64(KEY) + '</wst:BinarySecret></wst:RequestedProofToken>'
                 '</wst:RequestSecurityTokenResponse></Envelope>')
        return clear.encode(), _parse(clear)
    client._post = respond
    device = client.provision_device()
    assert device.puid == 'device-puid' and device.da.session_key == KEY
    assert len(calls) == 2
    assert b'wsu:Id="devicesoftware"' in calls[1][1]
    assert device.password not in repr(device)


def test_user_keys_retrieval_uses_login_proof_and_strong_credential_key():
    from lxml import etree
    client = SoapClient()
    captured = {}
    def respond(url, root):
        captured['xml'] = etree.tostring(root)
        result = ('<Envelope xmlns:ps="http://schemas.microsoft.com/Passport/SoapServices/PPCRL">'
                  '<ps:GetKeyDataResponse Success="true"><ps:KeyPurposes>'
                  '<ps:KeyPurpose name="StrongCredentialKey"><ps:KeyData>'
                  '<ps:Property name="TimeStamp">key-id</ps:Property>'
                  '<ps:Property name="KeyMaterial">' + b64(b'k' * 16) + '</ps:Property>'
                  '</ps:KeyData></ps:KeyPurpose></ps:KeyPurposes></ps:GetKeyDataResponse></Envelope>')
        return result.encode(), _parse(result)
    client._post = respond
    device = DeviceIdentity('device', 'password', 'puid', DAToken('<EncryptedData xmlns="' + ENC + '"/>', KEY))
    assert client.get_user_keys(device, 'login-proof') == {'key-id': b64(b'k' * 16)}
    assert b'ValueType="ps:LoginProofToken"' in captured['xml']
    assert b'ValueType="urn:liveid:device"' in captured['xml']
    assert b'>StrongCredentialKey<' in captured['xml']
    assert b'<Signature' in captured['xml']


def test_force_signin_code_is_preserved_without_returning_error_body():
    client = SoapClient()
    response = b'<Envelope><GetKeyDataResponse Success="false"><Error Code="secret-body"/><ErrorSubcode>8004100c</ErrorSubcode></GetKeyDataResponse></Envelope>'
    client._post = lambda *args: (response, _parse(response))
    device = DeviceIdentity('device', 'password', 'puid', DAToken('<EncryptedData xmlns="' + ENC + '"/>', KEY))
