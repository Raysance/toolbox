KEY = bytes(range(32))
NONCE = bytes(range(32, 64))
# Generated by compiling the APK's SharedKeyGenerator.java with JDK 21.
STS_KEY = bytes.fromhex("fc97fd9753a37f50a29a9fa0c80da7ec37ee6c8dad1701de7fa8350e712dadf4")
DS = "http://www.w3.org/2000/09/xmldsig#"
ENC = "http://www.w3.org/2001/04/xmlenc#"
WSU = "http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-utility-1.0.xsd"
S = "http://www.w3.org/2003/05/soap-envelope"
WST = "http://schemas.xmlsoap.org/ws/2005/02/trust"


def b64(value):
    return base64.b64encode(value).decode()


def encrypt(clear):
    iv = bytes(range(16))
    p = padding.PKCS7(128).padder()
    padded = p.update(clear.encode()) + p.finalize()
    c = Cipher(algorithms.AES(STS_KEY), modes.CBC(iv)).encryptor()
    return b64(iv + c.update(padded) + c.finalize())


def signed_fixture(*, url=None, ticket=True):
    """Construct server-style raw-XML signatures independently of SDK serializer."""
    pp = ('<psf:pp xmlns:psf="http://schemas.microsoft.com/Passport/SoapServices/SOAPFault">'
          '<psf:PUID>test-puid</psf:PUID><psf:credProperties>'
          '<psf:credProperty Name="CID">0123456789abcdef</psf:credProperty>'
          '</psf:credProperties>' +
          ('<psf:inlineauthurl>' + url + '</psf:inlineauthurl>' if url else '') + '</psf:pp>')
    # The synthetic DA EncryptedData is opaque to the SDK, as it is in a real response.
    da = ('<wst:RequestSecurityTokenResponse><wst:TokenType>urn:passport:legacy</wst:TokenType>'
          '<wst:Lifetime><wsu:Expires>2099-01-01T00:00:00Z</wsu:Expires></wst:Lifetime>'
          '<wsp:AppliesTo><wsa:EndpointReference><wsa:Address>http://Passport.NET/tb</wsa:Address>'
          '</wsa:EndpointReference></wsp:AppliesTo><wst:RequestedSecurityToken>'
          '<EncryptedData xmlns="' + ENC + '"><CipherData><CipherValue>opaque</CipherValue>'
          '</CipherData></EncryptedData></wst:RequestedSecurityToken><wst:RequestedProofToken>'
          '<wst:BinarySecret>' + b64(b"k" * 32) + '</wst:BinarySecret></wst:RequestedProofToken>'
          '</wst:RequestSecurityTokenResponse>')
    compact = ('<wst:RequestSecurityTokenResponse><wst:TokenType>urn:passport:compact</wst:TokenType>'
          '<wst:Lifetime><wsu:Expires>2099-01-01T00:00:00Z</wsu:Expires></wst:Lifetime>'
          '<wsp:AppliesTo><wsa:EndpointReference><wsa:Address>scope=test</wsa:Address>'
          '</wsa:EndpointReference></wsp:AppliesTo><wst:RequestedSecurityToken>'
          '<wsse:BinarySecurityToken>test-ticket</wsse:BinarySecurityToken>'
          '</wst:RequestedSecurityToken></wst:RequestSecurityTokenResponse>') if ticket else ''
    collection = ('<wst:RequestSecurityTokenResponseCollection xmlns:wst="' + WST + '" '
        'xmlns:wsu="' + WSU + '" xmlns:wsp="http://schemas.xmlsoap.org/ws/2004/09/policy" '
        'xmlns:wsa="http://www.w3.org/2005/08/addressing" '
        'xmlns:wsse="http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-secext-1.0.xsd">'
        + da + compact + '</wst:RequestSecurityTokenResponseCollection>')
    encrypted_pp = '<EncryptedData xmlns="' + ENC + '" Id="pp"><CipherData><CipherValue>' + encrypt(pp) + '</CipherValue></CipherData></EncryptedData>'
    body = '<S:Body Id="body"><EncryptedData xmlns="' + ENC + '"><CipherData><CipherValue>' + encrypt(collection) + '</CipherValue></CipherData></EncryptedData></S:Body>'
    timestamp = '<wsu:Timestamp xmlns:wsu="' + WSU + '" Id="Timestamp"><wsu:Expires>2099-01-01T00:00:00Z</wsu:Expires></wsu:Timestamp>'
    refs = ''
    for ident, value in [('pp', encrypted_pp), ('body', body), ('Timestamp', timestamp)]:
        refs += ('<Reference URI="#' + ident + '"><DigestMethod Algorithm="' + ENC + 'sha256"></DigestMethod>'
                 '<DigestValue>' + b64(hashlib.sha256(value.encode()).digest()) + '</DigestValue></Reference>')
    info = ('<SignedInfo xmlns="' + DS + '"><CanonicalizationMethod Algorithm="http://www.w3.org/2001/10/xml-exc-c14n#"></CanonicalizationMethod>'
            '<SignatureMethod Algorithm="http://www.w3.org/2001/04/xmldsig-more#hmac-sha256"></SignatureMethod>' + refs + '</SignedInfo>')
    signature = '<Signature xmlns="' + DS + '">' + info + '<SignatureValue>' + b64(hmac.new(STS_KEY, info.encode(), hashlib.sha256).digest()) + '</SignatureValue></Signature>'
    derived = ''.join('<wssc:DerivedKeyToken wsu:Id="' + kind + '"><wssc:Nonce>' + b64(NONCE) + '</wssc:Nonce></wssc:DerivedKeyToken>' for kind in ('EncKey', 'SignKey'))
    return ('<S:Envelope xmlns:S="' + S + '" xmlns:wsu="' + WSU + '" '
            'xmlns:wsse="http://docs.oasis-open.org/wss/2004/01/oasis-200401-wss-wssecurity-secext-1.0.xsd" '
            'xmlns:wssc="http://schemas.xmlsoap.org/ws/2005/02/sc" '
            'xmlns:psf="http://schemas.microsoft.com/Passport/SoapServices/SOAPFault">'
            '<S:Header><wsse:Security>' + timestamp + derived + signature + '</wsse:Security>'
            '<psf:EncryptedPP>' + encrypted_pp + '</psf:EncryptedPP></S:Header>' + body + '</S:Envelope>').encode()


